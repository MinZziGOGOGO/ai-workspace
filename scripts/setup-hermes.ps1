<#
.SYNOPSIS
  One-time installer for the Hermes Agent (Milestone 6).

.DESCRIPTION
  Stands up everything the Hermes tab needs, then never has to run again:

    1. Ensures an Ubuntu distro exists in WSL2 (installs it if missing).
    2. Installs uv inside Ubuntu (if not already present).
    3. Installs Hermes Agent with `uv tool install hermes-agent`.
    4. Writes ~/.hermes/config.yaml: model provider = Windows-host Ollama
       (http://host.docker.internal:11434/v1, OpenAI-compatible endpoint).
       The knowledge MCP server is now wired per-session by the app via the
       ACP `session/new` mcpServers field - no static config needed.
    5. Verifies `hermes acp --check` passes (ACP adapter imports OK).
    6. Drops a ~/.ai-workspace-hermes/installed timestamp the app probes
       (src/main/hermes.ts checkHermes()).

  IMPLEMENTATION NOTE - every Linux command runs inside `wsl -d <distro> -- bash -lc
  "<cmd>"`. Those command strings are built as PowerShell *single-quoted* literals
  (so bash `$`, `$()`, `||`, `&&` are never seen by the PowerShell parser); the
  model name is injected by .Replace() on placeholder tokens. No bash-style
  operators appear at the PowerShell statement level.

.NOTES
  Run once from anywhere:
    powershell -ExecutionPolicy Bypass -File scripts/setup-hermes.ps1
#>

[CmdletBinding()]
param(
  [string]$Distro = 'Ubuntu',
  [string]$OllamaUrl = 'http://host.docker.internal:11434'
)

$ErrorActionPreference = 'Stop'

function Info($m) { Write-Host "[hermes-setup] $m" -ForegroundColor Cyan }
function Ok($m)   { Write-Host "[hermes-setup] $m" -ForegroundColor Green }
function Warn($m) { Write-Host "[hermes-setup] $m" -ForegroundColor Yellow }
function Die($m)  { Write-Host "[hermes-setup] $m" -ForegroundColor Red; exit 1 }

# Run a bash command inside the WSL distro. The command is one PowerShell string,
# passed as a single argument after `-lc`. All bash operators live inside $Cmd.
function Invoke-WslBash {
  param(
    [Parameter(Mandatory = $true)][string]$Cmd,
    [switch]$AllowFail
  )
  & wsl.exe -d $Distro -- bash -lc $Cmd
  if (-not $AllowFail -and $LASTEXITCODE -ne 0) {
    Die "WSL command failed (exit $LASTEXITCODE)."
  }
}

# --- 0. Pre-flight: WSL present? -----------------------------------------------
try {
  & wsl.exe --status | Out-Null
} catch {
  Die "WSL is not installed. Open an admin PowerShell, run 'wsl --install', reboot, then re-run this script."
}

# --- 1. Ensure the Ubuntu distro exists ----------------------------------------
# `wsl -l -q` emits UTF-16; PowerShell decodes it. Match the chosen distro name.
$installed = (& wsl.exe -l -q) | ForEach-Object { $_.Trim() } | Where-Object { $_ }
if (-not ($installed -contains $Distro)) {
  Info "Installing the '$Distro' distro into WSL2 (this can take several minutes)..."
  & wsl.exe --install -d $Distro
  Warn "If this is the first Linux distro, Windows may need a reboot and a one-time UNIX user setup."
  Warn "Complete any prompt that appears, then re-run this script."
  $installed = (& wsl.exe -l -q) | ForEach-Object { $_.Trim() } | Where-Object { $_ }
  if (-not ($installed -contains $Distro)) {
    Die "Ubuntu is not ready yet. Finish its first-run setup, then re-run."
  }
}
Ok "WSL2 distro '$Distro' is present."

# --- 2. Pick the default model from Ollama ------------------------------------
# MCP server wiring is now done per-session by the app (ACP session/new); no
# cross-boundary path resolution needed here any more.
$Model = 'gemma4:12b'
try {
  $rows = (& ollama list) | Select-Object -Skip 1 | Where-Object { $_.Trim() }
  $first = $rows | ForEach-Object { ($_ -split '\s+')[0] } |
    Where-Object { $_ -and ($_ -notmatch 'embed') } | Select-Object -First 1
  if ($first) { $Model = $first }
} catch {
  Warn "Could not query 'ollama list'; defaulting model to $Model."
}
Info "default model: $Model"

# --- 3. Install uv + Hermes Agent inside Ubuntu --------------------------------
Info "Installing uv inside '$Distro' (if missing)..."
Invoke-WslBash 'command -v uv >/dev/null 2>&1 || curl -LsSf https://astral.sh/uv/install.sh | sh'

Info "Installing Hermes Agent (uv tool install hermes-agent)..."
# Primary install from PyPI; fall back to the GitHub source if not published.
Invoke-WslBash 'export PATH="$HOME/.local/bin:$PATH"; uv tool install hermes-agent || uv tool install "git+https://github.com/NousResearch/hermes-agent.git"'
Ok "Hermes Agent installed."

# --- 4. Write ~/.hermes/config.yaml --------------------------------------------
# Only the model provider section is needed; MCP server wiring is passed by the
# app at runtime via ACP session/new (no static path baked in at install time).
$yaml = @'
# Hermes Agent config - generated by scripts/setup-hermes.ps1 (AI Workspace M6).
# Model provider: Windows-host Ollama via the OpenAI-compatible endpoint.
model:
  provider: openai
  base_url: __OLLAMA__/v1
  api_key: ollama
  model: __MODEL__
'@
$yaml = $yaml.Replace('__OLLAMA__', $OllamaUrl)
$yaml = $yaml.Replace('__MODEL__',  $Model)

# Base64-encode the YAML (LF-normalised, UTF-8) and decode it inside bash.
# Avoids all temp-file / wslpath / backslash-stripping issues.
Info "Writing ~/.hermes/config.yaml inside '$Distro'..."
$yamlB64 = [Convert]::ToBase64String([System.Text.Encoding]::UTF8.GetBytes(($yaml -replace "`r`n", "`n")))
Invoke-WslBash ("mkdir -p ~/.hermes && printf '%s' '" + $yamlB64 + "' | base64 -d > ~/.hermes/config.yaml")
Ok "Wrote ~/.hermes/config.yaml (model: $Model, Ollama: $OllamaUrl)."

# --- 5. Verify ACP adapter and write installed marker -------------------------
Info "Verifying ACP adapter (hermes acp --check)..."
Invoke-WslBash 'export PATH="$HOME/.local/bin:$PATH"; hermes acp --check'
Ok "ACP adapter check passed."

Invoke-WslBash 'mkdir -p ~/.ai-workspace-hermes && date -u +%Y-%m-%dT%H:%M:%SZ > ~/.ai-workspace-hermes/installed'
Ok "Wrote ~/.ai-workspace-hermes/installed marker."

Write-Host ''
Ok "SUCCESS: Hermes is installed and ready."
Ok "Open the Hermes tab in the app and click Connect to start a session."
exit 0
